local RotableItemClasses = {}
RotableItemClasses.last_class = 0
RotableItemClasses.from_itemid_to_class = {}

local data = { storeIndex }
for _, category in pairs(data[1]) do
    for _, offer in pairs(category.offers) do
        if offer.type == GameStore_OfferTypes.OFFER_TYPE_ITEM then
            
            local item = ItemType(offer.id)
            if item then
                local class
                if RotableItemClasses.from_itemid_to_class[offer.id] then
                    class = RotableItemClasses.from_itemid_to_class[offer.id]
                else
                    RotableItemClasses.last_class = RotableItemClasses.last_class + 1 -- Cria nova classe
                    class = RotableItemClasses.last_class
                end

                local function search_for_rotatable(previousItem, id)
                    RotableItemClasses.from_itemid_to_class[id] = class
                    local rotatedItem = previousItem:rotateTo()
                    if rotatedItem > 0 then
                        if not RotableItemClasses.from_itemid_to_class[rotatedItem] then
                            local nextItem = ItemType(rotatedItem)
                            if nextItem then
                                search_for_rotatable(nextItem, rotatedItem)
                            end
                        end
                    end
                end

                search_for_rotatable(item, offer.id)

                
            end
        end
    end
end

RotableItemClasses.from_class_to_items = {}

for itemId, class in pairs(RotableItemClasses.from_itemid_to_class) do
    if not RotableItemClasses.from_class_to_items[class] then
        RotableItemClasses.from_class_to_items[class] = {}
    end

    table.insert(RotableItemClasses.from_class_to_items[class], itemId)
end

function getItemRotateClassById(itemid)
    return RotableItemClasses.from_itemid_to_class[itemid]
end